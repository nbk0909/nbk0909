"""أدوات معالجة النص العربي.

تُستخدم في البحث الذكي وفي عرض الأرقام والترتيب الأبجدي.
النسخة نفسها من منطق التطبيع موجودة كدالة SQL في database/schema.sql
لضمان تطابق نتائج البحث بين طبقة التطبيق وطبقة قاعدة البيانات.
"""

from __future__ import annotations

import re
import unicodedata

# ---------------------------------------------------------------------------
# جداول التحويل
# ---------------------------------------------------------------------------

# توحيد صور الحروف المتشابهة
_CHAR_MAP = str.maketrans(
    {
        # صور الألف
        "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ٲ": "ا", "ٳ": "ا",
        # الهمزات على واو وياء
        "ؤ": "و", "ئ": "ي",
        # التاء المربوطة
        "ة": "ه",
        # الألف المقصورة
        "ى": "ي",
        # الكاف والياء الفارسية
        "ک": "ك", "ي": "ي", "ی": "ي",
        # الأرقام العربية-الهندية إلى اللاتينية
        "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
        "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
    }
)

# التشكيل والتطويل: الفتحتان..السكون + الشدة + التطويل + العلامات القرآنية
_DIACRITICS_RE = re.compile(r"[ؐ-ًؚ-ٰٟۖ-ۭـ]")

# كل ما ليس حرفاً عربياً أو لاتينياً أو رقماً أو مسافة
_PUNCT_RE = re.compile(r"[^ء-يa-zA-Z0-9\s]")

_WHITESPACE_RE = re.compile(r"\s+")

# الأرقام العربية-الهندية للعرض
_ARABIC_DIGITS = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")
_LATIN_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789")


# ---------------------------------------------------------------------------
# التطبيع
# ---------------------------------------------------------------------------

def normalize_arabic(text: str | None) -> str | None:
    """يُطبِّع النص العربي لأغراض البحث والمقارنة.

    يحذف التشكيل والتطويل، ويوحّد صور الألف (أ إ آ ← ا) والتاء المربوطة
    (ة ← ه) والألف المقصورة (ى ← ي)، ويضغط المسافات.

    >>> normalize_arabic("أَحْمَد عَلِيّ")
    'احمد علي'
    >>> normalize_arabic("فاطمة الزهراء")
    'فاطمه الزهراء'
    """
    if text is None:
        return None

    # توحيد صور اليونيكود المركّبة قبل أي معالجة
    text = unicodedata.normalize("NFKC", text)
    text = _DIACRITICS_RE.sub("", text)
    text = text.translate(_CHAR_MAP)
    text = _PUNCT_RE.sub(" ", text)
    text = _WHITESPACE_RE.sub(" ", text)
    return text.strip()


def normalize_for_search(text: str | None) -> str:
    """نسخة من التطبيع تُرجع نصاً فارغاً بدل None — مناسبة لبناء الاستعلامات."""
    return normalize_arabic(text) or ""


# ---------------------------------------------------------------------------
# الأرقام
# ---------------------------------------------------------------------------

def to_arabic_numerals(text: str) -> str:
    """يحوّل الأرقام اللاتينية إلى عربية-هندية (123 ← ١٢٣)."""
    return text.translate(_ARABIC_DIGITS)


def to_latin_numerals(text: str) -> str:
    """يحوّل الأرقام العربية-الهندية إلى لاتينية (١٢٣ ← 123)."""
    return text.translate(_LATIN_DIGITS)


# ---------------------------------------------------------------------------
# الترتيب الأبجدي العربي
# ---------------------------------------------------------------------------

# ترتيب حروف الهجاء العربي (الترتيب الألفبائي المشرقي)
_ALPHABET = "ابتثجحخدذرزسشصضطظعغفقكلمنهوي"
_ORDER = {ch: idx for idx, ch in enumerate(_ALPHABET)}


def arabic_sort_key(name: str) -> tuple:
    """مفتاح ترتيب يرتّب الأسماء العربية حسب ترتيب الهجاء الصحيح.

    الترتيب الافتراضي في بايثون يعتمد على قيم اليونيكود، وهي لا تطابق
    ترتيب حروف الهجاء المتعارف عليه (الهمزات مثلاً تسبق الألف).

    >>> sorted(["يوسف", "أحمد", "خالد"], key=arabic_sort_key)
    ['أحمد', 'خالد', 'يوسف']
    """
    normalized = normalize_arabic(name) or ""
    # الحروف غير المعروفة تُوضع في نهاية الترتيب
    return tuple(_ORDER.get(ch, len(_ALPHABET)) for ch in normalized)


# ---------------------------------------------------------------------------
# تشكيل النص للطباعة في PDF
# ---------------------------------------------------------------------------

def shape_for_pdf(text: str) -> str:
    """يعيد تشكيل النص العربي ويطبّق خوارزمية BiDi لعرضه صحيحاً في PDF.

    مكتبات توليد PDF لا تدعم ربط الحروف العربية ولا اتجاه النص، فيظهر
    النص مقطّعاً ومعكوساً ما لم يُعالَج مسبقاً.
    """
    try:
        import arabic_reshaper
        from bidi.algorithm import get_display
    except ImportError:  # pragma: no cover - يعتمد على بيئة التشغيل
        return text

    return get_display(arabic_reshaper.reshape(text))
