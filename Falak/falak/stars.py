def star_apparent(star, jde):
    """الموقع الظاهري لنجم: يعيد (مطلع مستقيم، ميل) بالدرجات.

    تُطبَّق الحركة الذاتية ثم التقديم من J2000 إلى تاريخ الرصد،
    ثم الانحراف السنوي والتقلقل.
    """
    years = (jde - J2000) / 365.25

    dec = star.dec_j2000 + star.pm_dec / 3600000.0 * years
    cos_dec = cosd(star.dec_j2000)
    if abs(cos_dec) < 1e-8:
        ra = star.ra_j2000
    else:
        ra = star.ra_j2000 + (star.pm_ra / 3600000.0 / cos_dec) * years

    vector = spherical_to_vector(norm360(ra), dec, 1.0)

    # الانحراف السنوي: إضافة نسبة سرعة الأرض إلى سرعة الضوء
    velocity = _ecliptic_to_equatorial_vector(earth_velocity(jde))
    vector = tuple(vector[i] + velocity[i] / LIGHT_SPEED_AU_PER_DAY
                   for i in range(3))

    t = julian_centuries(jde)
    vector = apply_matrix(precession_matrix(t), vector)
    lon, lat, _ = vector_to_spherical(vector)
    return apply_nutation_equatorial(lon, lat, t)


def find_stars(query):
    """البحث في الفهرس بالاسم العربي أو اللاتيني أو الكوكبة."""
    query = query.strip()
    if not query:
        return []
    lowered = query.lower()
    result = []
    for star in STARS:
        haystack = " ".join([star.name_ar, star.name_lat, star.bayer,
                             star.constellation_ar]).lower()
        if lowered in haystack:
            result.append(star)
    return result


def brightest(count=15):
    """ألمع النجوم في الفهرس مرتبة تصاعديًا حسب القدر."""
    return sorted(STARS, key=lambda s: s.magnitude)[:count]
