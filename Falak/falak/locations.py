class Observer(object):
    """راصد في موقع جغرافي محدد."""

    __slots__ = ("name", "latitude", "longitude", "elevation", "tz_offset",
                 "country")

    def __init__(self, name, latitude, longitude, tz_offset=0.0,
                 elevation=0.0, country=""):
        self.name = name
        self.latitude = float(latitude)
        self.longitude = float(longitude)
        self.tz_offset = float(tz_offset)
        self.elevation = float(elevation)
        self.country = country

    def describe(self):
        """وصف نصي مختصر للموقع بالعربية."""
        lat_dir = "شمالًا" if self.latitude >= 0 else "جنوبًا"
        lon_dir = "شرقًا" if self.longitude >= 0 else "غربًا"
        sign = "+" if self.tz_offset >= 0 else "-"
        hours = int(abs(self.tz_offset))
        minutes = int(round((abs(self.tz_offset) - hours) * 60))
        return ("%s — %.4f° %s، %.4f° %s — التوقيت المحلي UTC%s%02d:%02d"
                % (self.name, abs(self.latitude), lat_dir,
                   abs(self.longitude), lon_dir, sign, hours, minutes))

    def to_dict(self):
        return {
            "name": self.name, "latitude": self.latitude,
            "longitude": self.longitude, "tz_offset": self.tz_offset,
            "elevation": self.elevation, "country": self.country,
        }

    @classmethod
    def from_dict(cls, data):
        return cls(data.get("name", "موقع مخصص"),
                   data.get("latitude", 0.0), data.get("longitude", 0.0),
                   data.get("tz_offset", 0.0), data.get("elevation", 0.0),
                   data.get("country", ""))


