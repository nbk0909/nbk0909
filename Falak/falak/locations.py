def find_city(query):
    """البحث عن مدينة بالاسم (مطابقة جزئية)."""
    query = query.strip()
    if not query:
        return []
    exact = [c for c in CITIES if c.name == query]
    if exact:
        return exact
    return [c for c in CITIES if query in c.name or query in c.country]


